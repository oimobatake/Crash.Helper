using Crash.Helper.Memory.Runtime;

namespace Crash.Helper.Memory.Camera
{
    // Follow advances once per rendered game frame, using the live actor and the game's delta time.
    internal static class CameraFollowCode
    {
        internal static void Emit(RuntimeCode c, long header)
        {
            c.Data(0, 0x48, 0x8B, 0x05); c.Rip(header + 128, 0x48, 0x3B, 0x05); c.Branch("followInit", 0x0F, 0x85);
            c.Data(216, 0x48, 0x8B, 0x05); c.Rip(header + 136, 0x48, 0x3B, 0x05); c.Branch("followReady", 0x0F, 0x84);
            c.Label("followInit");
            c.Data(0, 0x48, 0x8B, 0x05); c.Rip(header + 128, 0x48, 0x89, 0x05);
            c.Data(216, 0x48, 0x8B, 0x05); c.Rip(header + 136, 0x48, 0x89, 0x05);
            for (int i = 0; i < 3; i++) { c.Data(32 + i * 4, 0x8B, 0x05); c.Rip(header + 144 + i * 4, 0x89, 0x05); }
            c.Data(152, 0x8B, 0x05); c.Rip(header + 156, 0x89, 0x05);
            c.Label("followReady");
            c.Data(152, 0xF3, 0x0F, 0x10, 0x05); c.Rip(header + 156, 0xF3, 0x0F, 0x5C, 0x05);
            c.Data(188, 0xF3, 0x0F, 0x10, 0x15); c.Emit(0x0F, 0x2F, 0xC2); c.Branch("followAbove", 0x0F, 0x87);
            c.Emit(0x0F, 0x57, 0xDB, 0xF3, 0x0F, 0x5C, 0xDA, 0x0F, 0x2F, 0xC3); c.Branch("followBelow", 0x0F, 0x82); c.Branch("followBlend", 0xE9);
            c.Label("followAbove"); c.Data(152, 0xF3, 0x0F, 0x10, 0x05); c.Emit(0xF3, 0x0F, 0x5C, 0xC2); c.Branch("followHeight", 0xE9);
            c.Label("followBelow"); c.Data(152, 0xF3, 0x0F, 0x10, 0x05); c.Emit(0xF3, 0x0F, 0x58, 0xC2);
            c.Label("followHeight"); c.Rip(header + 156, 0xF3, 0x0F, 0x11, 0x05);
            c.Label("followBlend");
            c.Data(200, 0xF3, 0x0F, 0x10, 0x25); c.Data(192, 0xF3, 0x0F, 0x10, 0x1D);
            c.Data(196, 0x0F, 0x2F, 0x1D); c.Branch("followAxes", 0x0F, 0x86);
            c.Data(240, 0x48, 0x8B, 0x05); c.Emit(0xF3, 0x0F, 0x10, 0x40, 0x28);
            c.Data(196, 0xF3, 0x0F, 0x5F, 0x05); c.Data(224, 0xF3, 0x0F, 0x5D, 0x05); c.Emit(0xF3, 0x0F, 0x59, 0xD8);
            // A positive reciprocal polynomial approximates exp(-rate * dt), without a CRT dependency.
            c.Data(212, 0xF3, 0x0F, 0x10, 0x2D);
            foreach (int offset in new[] { 208, 204, 200, 200 })
            { c.Emit(0xF3, 0x0F, 0x59, 0xEB); c.Data(offset, 0xF3, 0x0F, 0x58, 0x2D); }
            c.Emit(0x0F, 0x28, 0xC4, 0xF3, 0x0F, 0x5E, 0xC5, 0xF3, 0x0F, 0x5C, 0xE0);
            c.Label("followAxes");
            for (int i = 0; i < 3; i++)
            {
                if (i == 2) c.Rip(header + 156, 0xF3, 0x0F, 0x10, 0x05);
                else c.Data(144 + i * 4, 0xF3, 0x0F, 0x10, 0x05);
                c.Data(56, 0xF3, 0x0F, 0x59, 0x05); c.Data(176 + i * 4, 0xF3, 0x0F, 0x58, 0x05);
                c.Rip(header + 144 + i * 4, 0xF3, 0x0F, 0x5C, 0x05); c.Emit(0xF3, 0x0F, 0x59, 0xC4);
                c.Rip(header + 144 + i * 4, 0xF3, 0x0F, 0x58, 0x05); c.Rip(header + 144 + i * 4, 0xF3, 0x0F, 0x11, 0x05);
                c.Emit(0xF3, 0x41, 0x0F, 0x11, 0x47, (byte)(i * 4));
            }
        }
    }
}
